const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('rb', {
  loadStatic: () => ipcRenderer.invoke('static:load'),
  listPages: () => ipcRenderer.invoke('pages:list'),
  savePage: (page) => ipcRenderer.invoke('pages:save', page),
  deletePage: (id) => ipcRenderer.invoke('pages:delete', id),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  reportBug: (text) => ipcRenderer.invoke('bug:report', text),
  logError: (text) => ipcRenderer.invoke('log:error', text),
  getLcuState: () => ipcRenderer.invoke('lcu:state'),
  applyPage: (pageId, replaceId, perkIds) => ipcRenderer.invoke('lcu:apply', pageId, replaceId, perkIds),
  applyRawPage: (page, replaceId) => ipcRenderer.invoke('lcu:applyRaw', page, replaceId),
  getRecommended: (championKey) => ipcRenderer.invoke('lcu:recommended', championKey),
  getCurrentPage: () => ipcRenderer.invoke('lcu:currentPage'),
  getAllRecommended: () => ipcRenderer.invoke('rec:all'),
  onRecProgress: (cb) => ipcRenderer.on('rec:progress', (_e, p) => cb(p)),
  onPagesChanged: (cb) => ipcRenderer.on('pages:changed', () => cb()),
  onStaticUpdated: (cb) => ipcRenderer.on('static:updated', () => cb()),
  onRecUpdated: (cb) => ipcRenderer.on('rec:updated', (_e, pages) => cb(pages)),
  onLcuState: (cb) => ipcRenderer.on('lcu:state', (_e, s) => cb(s)),
  onToast: (cb) => ipcRenderer.on('toast', (_e, msg) => cb(msg)),
  getClientOffer: () => ipcRenderer.invoke('offer:get'),
  saveClientOffer: (championKey, mode) => ipcRenderer.invoke('offer:save', championKey, mode),
  dismissClientOffer: () => ipcRenderer.invoke('offer:dismiss'),
  popupFit: (w, h) => ipcRenderer.invoke('popup:fit', w, h),
  popupHide: () => ipcRenderer.invoke('popup:hide'),
  popupSticky: (v) => ipcRenderer.invoke('popup:sticky', v),
  getCurrentPageId: () => ipcRenderer.invoke('page:current'),
  openEditor: (pageId) => ipcRenderer.invoke('editor:open', pageId),
  getPendingEdit: () => ipcRenderer.invoke('editor:pending'),
  onEditPage: (cb) => ipcRenderer.on('editor:edit', (_e, id) => cb(id)),
  getButtonState: () => ipcRenderer.invoke('button:get'),
  clickButton: () => ipcRenderer.invoke('button:click'),
  buttonHover: (over) => ipcRenderer.invoke('button:hover', over),
  onButtonWarn: (cb) => ipcRenderer.on('button:warn', (_e, o) => cb(o)),
  onButtonWarnStop: (cb) => ipcRenderer.on('button:warnstop', () => cb()),
  onSettingsChanged: (cb) => ipcRenderer.on('settings:changed', (_e, st) => cb(st)),
  onButtonState: (cb) => ipcRenderer.on('button:state', (_e, st) => cb(st)),
  onPageApplied: (cb) => ipcRenderer.on('page:applied', (_e, id) => cb(id)),
  onClientOffer: (cb) => ipcRenderer.on('offer:changed', (_e, offer) => cb(offer)),
});
